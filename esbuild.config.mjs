import esbuild from 'esbuild';
import { builtinModules } from 'node:module';
import process from 'node:process';

const production = process.argv[2] === 'production';

const context = await esbuild.context({
  banner: {
    js: `/*
THIS IS A GENERATED/BUNDLED FILE.
Source: https://github.com/anightmonarch/obsidian-wechat-workbench
*/`,
  },
  entryPoints: ['src/main.ts'],
  bundle: true,
  external: [
    'obsidian',
    'electron',
    '@codemirror/autocomplete',
    '@codemirror/collab',
    '@codemirror/commands',
    '@codemirror/language',
    '@codemirror/lint',
    '@codemirror/search',
    '@codemirror/state',
    '@codemirror/view',
    '@lezer/common',
    '@lezer/highlight',
    '@lezer/lr',
    ...builtinModules,
  ],
  format: 'cjs',
  target: 'es2021',
  logLevel: 'info',
  sourcemap: production ? false : 'inline',
  treeShaking: true,
  outfile: 'main.js',
  minify: production,
});

if (production) {
  await context.rebuild();
  await context.dispose();
} else {
  await context.watch();
}
