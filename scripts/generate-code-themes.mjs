function unsafeSelector(selector) {
  return /(?:^|[\s>+~,(])(?:html|body)(?:[#.\s>+~,:]|$)|:root|:{1,2}(?:before|after|first-letter|first-line|marker|selection)\b/iu.test(selector);
}

function sanitizeCss(css, id) {
  const parsed = postcss.parse(css);
  const output = postcss.root();

  parsed.walkAtRules(rule => {
    rule.remove();
  });

  parsed.walkRules(rule => {
    const selectors = [];
    const processor = selectorParser(selectorRoot => {
      selectorRoot.each(selector => {
        const value = selector.toString().trim();
        if (!unsafeSelector(value)) selectors.push(value);
      });
    });
    processor.processSync(rule.selector);
    if (selectors.length === 0) return;

    const copy = rule.clone({ selector: selectors.join(',\n') });
    copy.walkDecls(declaration => {
      if (/url\s*\(/iu.test(declaration.value)) declaration.remove();
    });
    if (copy.nodes?.some(node => node.type === 'decl')) output.append(copy);
  });

  const result = output.toString().replace(/\r\n/gu, '\n').trim();
  if (!/\.hljs\b/iu.test(result)) {
    throw new Error(`${id}: sanitized stylesheet has no .hljs selector.`);
  }
  if (/url\s*\(|@import|@font-face/iu.test(result)) {
    throw new Error(`${id}: sanitized stylesheet still contains a remote or font resource.`);
  }
  return result;
}

function escapeTemplateLiteral(value) {
  return value.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${');
}

async function fileExists(path) {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

const entries = [];
for (const id of THEME_IDS) {
  const sourcePath = join(stylesDirectory, `${id}.css`);
  if (!(await fileExists(sourcePath))) throw new Error(`Missing highlight.js stylesheet: ${id}.css`);
  const source = await readFile(sourcePath, 'utf8');
  entries.push(`  ${JSON.stringify(id)}: \`${escapeTemplateLiteral(sanitizeCss(source, id))}\``);
}

const output = `/* Generated by scripts/generate-code-themes.mjs; do not edit by hand. */
export const GENERATED_CODE_THEMES: Readonly<Record<string, string>> = Object.freeze({
${entries.join(',\n')}
});
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, 'utf8');
