export const COVER_PROMPT_PRESETS: readonly Readonly<CoverPromptPreset>[] = Object.freeze(PRESET_ROWS.map(([id, name, body]) => Object.freeze({
  id,
  name,
  prompt: `请生成一张用于微信公众号文章的高级横版视觉封面。\n\n画布为 21:9。只生成纯视觉背景，不制作信息图、界面面板、截图、文档页、代码片段或品牌产品。\n\n视觉与主体：${body}`,
})));

export function coverPromptPreset(id: string): Readonly<CoverPromptPreset> {
  return COVER_PROMPT_PRESETS.find(preset => preset.id === id)
    ?? COVER_PROMPT_PRESETS.find(preset => preset.id === DEFAULT_COVER_PROMPT_PRESET_ID)!;
}
